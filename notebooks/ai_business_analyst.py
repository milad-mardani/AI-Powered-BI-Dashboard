# 13. Generate Initial Dashboard Summary
# ==========================================

def generate_dashboard_summary():

    print("\nGenerating initial dashboard summary...")

    analysis = route_question("business summary")

    if analysis is None:
        print("Could not generate the initial Business Summary.")
        return

    base_explanation = generate_rule_based_explanation(
        analysis
    )

    final_explanation, source, error = get_final_explanation(
        base_explanation
    )

    export_dashboard_summary(
        analysis,
        final_explanation,
        source
    )

    print("\nInitial Dashboard Summary:")
    print(final_explanation)

    if error:
        print("\nSummary Source:", source)
        print("AI Notice:", error)


