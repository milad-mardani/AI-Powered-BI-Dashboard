# 6. Rule-Based Business Explanation
# ==========================================

def generate_rule_based_explanation(analysis):

    metric = analysis["metric"]
    result = analysis["result"]

    if metric == "Cancellation Rate":
        return (
            "The cancellation rate represents the share "
            "of all orders that were cancelled. It should not "
            "be interpreted as a percentage of completed orders."
        )

    if metric == "Completion Rate":
        return (
            "The completion rate represents the share "
            "of all orders that reached the Completed status."
        )

    if metric == "Pending Rate":
        return (
            "The pending rate represents the share "
            "of all orders currently classified as Pending "
            "in the dataset."
        )

    if metric == "Average Order Value":
        return (
            "Average Order Value represents the average "
            "revenue generated per completed order. "
            "Only completed orders are included in this metric."
        )

    if metric == "Total Revenue":
        return (
            "This metric represents the total revenue "
            "generated by completed orders in the dataset."
        )

    if metric == "Total Orders":
        return (
            "This metric represents the total number "
            "of orders recorded in the dataset, "
            "regardless of their status."
        )

    if metric == "Order Status Analysis":
        return (
            "This analysis shows how orders are distributed "
            "across Completed, Pending, and Cancelled statuses. "
            "It provides an overview of the order status "
            "distribution in the dataset."
        )

    if metric == "Completed Orders":
        return (
            "This result represents the number of orders "
            "classified as Completed in the dataset."
        )

    if metric == "Pending Orders":
        return (
            "This result represents the number of orders "
            "classified as Pending in the dataset."
        )

    if metric == "Cancelled Orders":
        return (
            "This result represents the number of orders "
            "classified as Cancelled in the dataset."
        )

    if metric == "Best Product":
        product = result.get("product", "Unknown")
        return (
            f"{product} is the product with the highest "
            "recorded revenue in the dataset."
        )

    if metric == "Lowest Product":
        product = result.get("product", "Unknown")
        return (
            f"{product} is the product with the lowest "
            "recorded revenue in the dataset."
        )

    if metric == "Best Region":
        region = result.get("region", "Unknown")
        return (
            f"{region} is the region with the highest "
            "recorded revenue in the dataset."
        )

    if metric == "Best Month":
        month = format_month(result.get("month", "Unknown"))
        return (
            f"{month} is the month with the highest "
            "recorded revenue in the dataset."
        )

    if metric == "Revenue by Region":

        if not isinstance(result, list) or not result:
            return "Regional revenue data is unavailable."

        best = max(result, key=lambda item: item["revenue"])
        lowest = min(result, key=lambda item: item["revenue"])

        return (
            f"{best['region']} has the highest recorded "
            f"revenue among the regions, while "
            f"{lowest['region']} has the lowest. "
            "The figures above show the revenue for each region."
        )

    if metric == "Revenue by Product":

        if not isinstance(result, list) or not result:
            return "Product revenue data is unavailable."

        best = max(result, key=lambda item: item["revenue"])
        lowest = min(result, key=lambda item: item["revenue"])

        return (
            f"{best['product']} has the highest recorded "
            f"revenue among the products, while "
            f"{lowest['product']} has the lowest."
        )

    if metric == "Top 5 Products":

        if not isinstance(result, list) or not result:
            return "Top product data is unavailable."

        return (
            f"{result[0]['product']} ranks first in the displayed "
            "top products based on recorded revenue."
        )

    if metric == "Monthly Revenue Trend":

        if not isinstance(result, list) or not result:
            return "Monthly revenue data is unavailable."

        highest = max(result, key=lambda item: item["revenue"])
        lowest = min(result, key=lambda item: item["revenue"])

        return (
            f"{format_month(highest['month'])} recorded the highest "
            f"monthly revenue, while {format_month(lowest['month'])} "
            "recorded the lowest. Monthly revenue varied throughout "
            "the observed period. The dataset does not establish "
            "the reasons behind these changes."
        )

    if metric == "Product Revenue Share":
        return (
            "This analysis shows how each product contributes "
            "to the total recorded revenue. The displayed results "
            "can be used to compare the revenue contribution "
            "of different products."
        )

    if metric == "Business Summary":
        return (
            "The business summary provides an overview of "
            "order statuses, total revenue, average order value, "
            "product performance, regional revenue, and the "
            "highest-revenue month. All revenue figures are "
            "based on completed orders."
        )

    return (
        "The verified Python result is displayed above. "
        "It provides the available information for this metric."
    )


# ==========================================
# 7. AI Explanation
# ==========================================

def generate_ai_explanation(base_explanation):

    response = ollama.chat(
        model=MODEL_NAME,
        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT
            },
            {
                "role": "user",
                "content": (
                    "Rewrite this verified explanation "
                    "without adding new information:\n\n"
                    + base_explanation
                )
            }
        ],
        options={"temperature": 0}
    )

    return response["message"]["content"].strip()


# ==========================================
# 8. Validate AI Explanation
# ==========================================

def validate_ai_explanation(explanation):

    if not explanation:
        return False

    if re.search(r"\d", explanation):
        return False

    if any(symbol in explanation for symbol in ["$", "€", "£"]):
        return False

    forbidden_words = [
        "profit",
        "profitable",
        "profitability"
    ]

    explanation_lower = explanation.lower()

    for word in forbidden_words:

        if re.search(
            r"\b" + re.escape(word) + r"\b",
            explanation_lower
        ):
            return False

    return True


# ==========================================
# 9. Select Final Explanation
# ==========================================

def get_final_explanation(base_explanation):

    try:

        ai_explanation = generate_ai_explanation(
            base_explanation
        )

        if validate_ai_explanation(ai_explanation):
            return ai_explanation, "Ollama AI", None

        return (
            base_explanation,
            "Python Fallback",
            "AI response did not pass validation."
        )

    except Exception as error:

        return (
            base_explanation,
            "Python Fallback",
            str(error)
        )


# ==========================================
# 10. Export CSV for Power BI
# ==========================================

def export_powerbi_csv(
    output_file,
    question,
    analysis,
    explanation,
    source
):

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    fields = [
        "InsightTitle",
        "Question",
        "Metric",
        "Insight",
        "Source",
        "GeneratedAt"
    ]

    row = {
        "InsightTitle": "AI BUSINESS INSIGHTS",
        "Question": question,
        "Metric": analysis["metric"],
        "Insight": explanation,
        "Source": source,
        "GeneratedAt": datetime.now().strftime(
            "%Y-%m-%d %H:%M:%S"
        )
    }

    with open(
        output_file,
        mode="w",
        newline="",
        encoding="utf-8-sig"
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fields
        )

        writer.writeheader()
        writer.writerow(row)

    print("\nPower BI Export: Successful")
    print("Output File:", output_file)


